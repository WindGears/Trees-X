import assert from 'node:assert/strict'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { gunzipSync, gzipSync } from 'node:zlib'
import { DataUtils } from 'three'

const source = 'artifacts/car-showroom/cycles-r10'
const target = 'public/studio/cold-studio/cycles-r10'
const manifest = JSON.parse(await readFile(`${source}/manifest.json`, 'utf8'))
const reference = JSON.parse(
  await readFile('public/studio/cold-studio/baked-r10/manifest.json', 'utf8'),
)
assert.deepEqual(manifest.config, reference.config)
assert.equal(manifest.faceSize, 1024)
assert.equal(manifest.samples, 256)
const hash = (value) => createHash('sha256').update(value).digest('hex')
const orientation = []
const runtimeRecords = []
await mkdir(target, { recursive: true })
for (const record of manifest.records) {
  const bytes = await readFile(`${source}/${record.file}`),
    raw = gunzipSync(bytes)
  assert.equal(hash(bytes), record.sha256)
  assert.equal(hash(raw), record.rawSha256)
  assert.equal(raw.length, record.width * record.height * 16)
  if (record.role === 'specular') {
    const old = gunzipSync(
      await readFile('public/studio/cold-studio/baked-r10/specular.rgba32f.bin'),
    )
    // Check each emitter's center in actual numerical HDR, independent of tone mapping.
    for (const light of Object.values(manifest.config.lights)) {
      const delta = light.position.map((v, i) => v - manifest.config.capture.position[i])
      const length = Math.hypot(...delta)
      const x = Math.floor((Math.atan2(delta[2], delta[0]) / (2 * Math.PI) + 0.5) * record.width)
      const y = Math.floor((0.5 - Math.asin(delta[1] / length) / Math.PI) * record.height)
      const sample = (buffer, row) =>
        Array.from({ length: 3 }, (_, channel) =>
          buffer.readFloatLE((row * record.width + x) * 16 + channel * 4),
        )
      const current = sample(raw, y)
      orientation.push({
        light: light.id,
        pixel: [x, y],
        current,
        reference: sample(old, y),
        referenceFlipped: sample(old, record.height - 1 - y),
      })
      assert.ok(
        current.every((value) => Math.abs(value - light.radiance) < 0.05),
        `Cycles emitter direction/intensity mismatch: ${light.id}: ${current}`,
      )
      assert.ok(
        sample(old, record.height - 1 - y).every(
          (value) => Math.abs(value - light.radiance) < 0.05,
        ),
        'Existing WebGPU DataTexture row convention changed',
      )
    }
  }
  // The old WebGPU readback uses bottom-up equirect rows. Cycles face assembly
  // above was top-down; explicitly match the existing DataTexture contract.
  const oriented = Buffer.alloc(raw.length),
    stride = record.width * 16
  for (let row = 0; row < record.height; row++)
    raw.copy(
      oriented,
      row * stride,
      (record.height - 1 - row) * stride,
      (record.height - row) * stride,
    )
  const half = Buffer.alloc(raw.length / 2)
  let maxAbsoluteError = 0,
    maxRelativeError = 0
  for (let i = 0; i < raw.length / 4; i++) {
    const value = oriented.readFloatLE(i * 4)
    assert.ok(Number.isFinite(value) && value >= 0 && value <= 65504, 'Invalid HDR sample')
    const encoded = DataUtils.toHalfFloat(value)
    half.writeUInt16LE(encoded, i * 2)
    const error = Math.abs(DataUtils.fromHalfFloat(encoded) - value)
    maxAbsoluteError = Math.max(maxAbsoluteError, error)
    if (value > 0.001) maxRelativeError = Math.max(maxRelativeError, error / value)
  }
  assert.ok(maxRelativeError < 0.001, 'Half float must preserve radiance within 0.1%')
  const packed = gzipSync(half, { level: 9 }),
    file = record.file.replace('32f', '16f')
  await writeFile(`${target}/${file}`, packed)
  runtimeRecords.push({
    ...record,
    file,
    dataType: 'float16',
    bytes: packed.length,
    rawBytes: half.length,
    sha256: hash(packed),
    rawSha256: hash(half),
    maxAbsoluteError,
    maxRelativeError,
  })
}
manifest.records = runtimeRecords
manifest.orientation = orientation
manifest.method =
  'Cycles offline room radiance; native Principled approximation of Three Physical; not a floor lightmap'
manifest.colorSpace = 'linear-srgb'
manifest.encoding = 'gzip little-endian RGBA float16; opaque .bin extension'
manifest.orientationConvention =
  'bottom-up equirect rows, DataTexture flipY=false, matches r10 WebGPU capture'
await writeFile(`${target}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n')
await writeFile(
  'src/lib/workbench/rendering/carShowroom/cyclesRecords.ts',
  '// Generated by register-cold-studio-cycles.mjs.\nexport const cyclesStudioRecords = ' +
    JSON.stringify(manifest, null, 2) +
    ' as const\n',
)
console.log(JSON.stringify({ target, orientation, records: manifest.records }))
