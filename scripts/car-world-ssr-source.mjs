import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'

// Deliberately fail closed on Three upgrades. Regenerate, then rerun the GPU fixture.
const source = (
  await readFile('node_modules/three/examples/jsm/tsl/display/SSRNode.js', 'utf8')
).replace(/\r\n/g, '\n')
const expected = '0a662b0fda55c8a92a3f59c2389c772374fb1d55b5ea758d78a98dbc366a87b0'
if (createHash('sha256').update(source).digest('hex') !== expected)
  throw new Error('Unreviewed Three SSR source: world fallback generation refused')
const directory = 'src/lib/workbench/rendering/realtime/carReflection/vendor'
const destination = `${directory}/SSRWorldNode.js`
function replaceOnce(input, before, after) {
  if (input.split(before).length !== 2) throw new Error(`SSR seam not unique: ${before}`)
  return input.replace(before, after)
}
let generated = source
for (const [from, to] of [
  ['../utils/RNoise.js', 'three/addons/tsl/utils/RNoise.js'],
  ['../utils/SpecularHelpers.js', './SpecularHelpers.js'],
  ['./boxBlur.js', 'three/addons/tsl/display/boxBlur.js'],
  ['./ImportanceSampledEnvironment.js', 'three/addons/tsl/display/ImportanceSampledEnvironment.js'],
])
  generated = replaceOnce(generated, `'${from}'`, `'${to}'`)
generated = replaceOnce(
  generated,
  "\t\tsuper( 'vec4' );",
  "\t\tsuper( 'vec4' );\n\n\t\tthis.worldFallback = null;",
)
const marker =
  '\t\t\t// Screen-space ray missed: environment fallback (MIS when CDF env is set up).'
generated = replaceOnce(
  generated,
  marker,
  `			// Trees X: reuse THIS sample's direction and weight, only after an SSR miss.
			if ( this.stochastic === true && this.worldFallback !== null ) {

				If( hit.equal( 0 ), () => {

					const worldSample = this.worldFallback( {
						origin: worldPosition,
						direction: this._cameraWorldMatrix.mul( vec4( viewReflectDir, 0 ) ).xyz.normalize(),
						normal: this._cameraWorldMatrix.mul( vec4( viewNormal, 0 ) ).xyz.normalize(),
						roughness
					} ).toVar();
					If( worldSample.a.greaterThan( 0 ).and( worldSample.a.lessThan( ENV_RAY_LENGTH ) ), () => {

						hit.assign( 1 );
						output.assign( vec4( worldSample.rgb.mul( finalSampleWeight ), worldSample.a.mul( specDominantFactor ) ) );

					} );

				} );

			}

${marker}`,
)
generated = `// Generated by scripts/car-world-ssr-source.mjs; do not hand edit.\n// Three.js 0.185.1, MIT (see THREE-LICENSE.txt). Original source SHA-256: ${expected}\n${generated}`
const helperSource = (
  await readFile('node_modules/three/examples/jsm/tsl/utils/SpecularHelpers.js', 'utf8')
).replace(/\r\n/g, '\n')
const helperHash = 'cce8b1cffde0b7f7966a062d0d05b97318ce180f411c76fe3e25ebbef49e4220'
if (createHash('sha256').update(helperSource).digest('hex') !== helperHash)
  throw new Error('Unreviewed Three specular helper source')
const helper =
  `// Generated by scripts/car-world-ssr-source.mjs; Three.js 0.185.1 MIT.\n// Original SHA-256: ${helperHash}\n` +
  replaceOnce(
    helperSource.trimEnd() + '\n',
    `\tlet T = cross( up, N ).toVar();\n\tT = T.normalize().toVar();\n\tIf( T.length().lessThan( 1e-3 ), () => {\n\n\t\tT.assign( cross( vec3( 0, 1, 0 ), N ).normalize() );\n\n\t} );`,
    `\tconst T = cross( up, N ).toVar();\n\t// Test before normalization: normalize(vec3(0)) may produce NaN.\n\tIf( dot( T, T ).lessThan( 1e-12 ), () => {\n\n\t\tT.assign( cross( vec3( 0, 1, 0 ), N ) );\n\n\t} );\n\tT.assign( T.normalize() );`,
  )
if (process.argv.includes('--check')) {
  const actual = (await readFile(destination, 'utf8')).replace(/\r\n/g, '\n')
  if (actual !== generated) throw new Error('World SSR derivative differs from reviewed generation')
  if ((await readFile(`${directory}/SpecularHelpers.js`, 'utf8')).replace(/\r\n/g, '\n') !== helper)
    throw new Error('World SSR helper differs from reviewed generation')
  const license = (await readFile(`${directory}/THREE-LICENSE.txt`, 'utf8')).replace(/\r\n/g, '\n')
  if (license !== (await readFile('node_modules/three/LICENSE', 'utf8')).replace(/\r\n/g, '\n'))
    throw new Error('Three license differs from installed distribution')
  console.log('World SSR source matches pinned upstream, fallback seams and stable tangent fix')
} else {
  await mkdir(directory, { recursive: true })
  await writeFile(destination, generated)
  await writeFile(`${directory}/SpecularHelpers.js`, helper)
  await writeFile(`${directory}/THREE-LICENSE.txt`, await readFile('node_modules/three/LICENSE'))
}
