/* global window, btoa */
import assert from 'node:assert/strict'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { gzipSync } from 'node:zlib'
import { chromium, expect } from '@playwright/test'
import ts from 'typescript'
import { showroomUrl } from './reventon-showroom/model.mjs'
import { attachShowroomBridge, showroomState } from './reventon-showroom/browser.mjs'

// Run explicitly against the capture route, never against the baked candidate.
const base = process.env.TREES_BAKE_BASE ?? 'http://127.0.0.1:5181'
const directory = 'public/studio/cold-studio/baked-r10'
const hash = (value) => createHash('sha256').update(value).digest('hex')
const configSource = await readFile('src/lib/workbench/rendering/carShowroom/config.ts', 'utf8')
const configModule = ts.transpileModule(configSource, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
}).outputText
const { coldStudioConfig: config } = await import(
  'data:text/javascript;base64,' + Buffer.from(configModule).toString('base64')
)
assert.equal(config.revision, 10, 'New showroom inputs need a new immutable bake directory')
await mkdir(directory, { recursive: true })
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const records = []
try {
  await page.goto(showroomUrl(base, 'showroom'), { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('slider', { name: '灯板亮度 · 调试' })).toBeVisible({
    timeout: 240000,
  })
  await attachShowroomBridge(page)
  const state = await page.evaluate(showroomState)
  assert.equal(state.showroom.phase, 'ready')
  assert.equal(state.showroom.revision, config.revision)
  assert.equal(state.showroom.probe.totalFaceDraws, 12)
  for (const role of ['specular', 'indirect']) {
    const info = await page.evaluate((role) => {
      const scene = window.__demo.scene.scene.value
      const texture = role === 'specular' ? scene.environment : scene.userData.traceBackground
      const image = texture.image
      if (!(image.data instanceof Float32Array)) throw new Error('Expected captured Float32 HDR')
      return { width: image.width, height: image.height, bytes: image.data.byteLength }
    }, role)
    const chunks = []
    for (let offset = 0; offset < info.bytes; offset += 1024 * 1024) {
      const encoded = await page.evaluate(
        ({ role, offset }) => {
          const scene = window.__demo.scene.scene.value
          const texture = role === 'specular' ? scene.environment : scene.userData.traceBackground
          const data = texture.image.data
          const bytes = new Uint8Array(
            data.buffer,
            data.byteOffset + offset,
            Math.min(1024 * 1024, data.byteLength - offset),
          )
          let binary = ''
          for (let i = 0; i < bytes.length; i += 8192)
            binary += String.fromCharCode(...bytes.subarray(i, i + 8192))
          return btoa(binary)
        },
        { role, offset },
      )
      chunks.push(Buffer.from(encoded, 'base64'))
    }
    const raw = Buffer.concat(chunks)
    const data = gzipSync(raw, { level: 9 })
    const file = `${role}.rgba32f.bin`
    await writeFile(`${directory}/${file}`, data)
    records.push({
      role,
      file,
      width: info.width,
      height: info.height,
      bytes: data.length,
      rawBytes: raw.length,
      sha256: hash(data),
      rawSha256: hash(raw),
    })
  }
  const sourceFiles = [
    'config.ts',
    'geometry.ts',
    'tiles.ts',
    'lights.ts',
    'receiver.ts',
    'probe.ts',
    'assetRecords.ts',
  ]
  const sources = {}
  for (const file of sourceFiles)
    sources[file] = hash(await readFile(`src/lib/workbench/rendering/carShowroom/${file}`))
  const manifest = {
    version: 1,
    method: 'Three WebGPU static raster room capture; not path tracing or a lightmap',
    colorSpace: 'linear-srgb',
    encoding: 'gzip little-endian RGBA float32',
    config,
    sources,
    records,
    excludes: ['car', 'contact-shadow overlay', 'bloom', 'cutaway'],
  }
  await writeFile(`${directory}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n')
  await writeFile(
    'src/lib/workbench/rendering/carShowroom/bakedRecords.ts',
    '// Generated by scripts/bake-cold-studio-probes.mjs. Captured inputs are immutable.\n' +
      'export const bakedStudioRecords = ' +
      JSON.stringify(manifest, null, 2) +
      ' as const\n',
  )
  console.log(JSON.stringify({ directory, records }))
} finally {
  await browser.close()
}
